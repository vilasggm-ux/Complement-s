/* =====================================================
   VARIABLES
===================================================== */

let currentName = "";
let currentVibe = "";
let currentMode = "";
let currentPickup = null;

// Shuffled indexes waiting to be used
let unusedComplimentIndexes = [];
let unusedPickupIndexes = [];


/* =====================================================
   GET USER DETAILS
===================================================== */

function getUserDetails() {

    const nameInput = document.getElementById("name").value.trim();
    const vibe = document.getElementById("gender").value;

    if (nameInput === "") {
        alert("Hey! Enter your name first 😄");
        return false;
    }

    if (vibe === "") {
        alert("Choose your vibe first ✨");
        return false;
    }

    currentName = nameInput;
    currentVibe = vibe;

    return true;
}


/* =====================================================
   SCREEN SWITCHING
===================================================== */

function showScreen(screenId) {

    const screens = document.querySelectorAll(".screen");

    screens.forEach(screen => {
        screen.classList.remove("active");
    });

    const targetScreen = document.getElementById(screenId);

    targetScreen.classList.add("active");

    // Restart animation
    targetScreen.style.animation = "none";

    setTimeout(() => {
        targetScreen.style.animation = "";
    }, 10);
}


/* =====================================================
   COMPLIMENT FLOW
===================================================== */

function giveCompliment() {

    if (!getUserDetails()) return;

    currentMode = "compliment";

    showRandomCompliment();

    document.body.classList.add("revealed");

    showScreen("complimentScreen");
}


